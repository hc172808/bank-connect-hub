import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = path.join(root, "supabase", "migrations");
const overridesPath = path.join(root, "supabase", "fresh-project-overrides.sql");
const outputPath = path.join(root, "SQL-update.sql");

function replaceExactlyOnce(source, search, replacement, label) {
  const first = source.indexOf(search);
  if (first < 0 || source.indexOf(search, first + search.length) >= 0) {
    throw new Error(`Expected exactly one ${label} match while building SQL-update.sql`);
  }
  return source.slice(0, first) + replacement + source.slice(first + search.length);
}

function replaceOneMatch(source, expression, replacement, label) {
  const flags = expression.flags.includes("g") ? expression.flags : `${expression.flags}g`;
  const matches = [...source.matchAll(new RegExp(expression.source, flags))];
  if (matches.length !== 1) {
    throw new Error(`Expected exactly one ${label} match; found ${matches.length}`);
  }
  return source.replace(expression, replacement);
}

const files = (await readdir(migrationsDir))
  .filter((name) => name.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  throw new Error("No Supabase migrations were found.");
}

const initialRoleMigration = "20251120101748_1467c7e3-eaa3-43f0-a7c9-d6975422db3b.sql";
const activeSchemaRepair = "20260920110000_active_project_schema_repair.sql";
const reserveMigration = "20260917000000_bank-reserve-and-agent-distribution.sql";
const transformed = [];

for (const name of files) {
  let sql = await readFile(path.join(migrationsDir, name), "utf8");

  if (name === initialRoleMigration) {
    sql = replaceExactlyOnce(
      sql,
      "create type public.app_role as enum ('admin', 'agent', 'client');",
      "create type public.app_role as enum ('admin', 'agent', 'client', 'vendor', 'founder');",
      "initial app_role enum",
    );
  }

  if (name === activeSchemaRepair) {
    sql = replaceExactlyOnce(
      sql,
      "WHERE user_id = _user_id AND role = _role",
      "WHERE user_id = _user_id AND role::text = _role",
      "text has_role comparison against the fresh-install enum",
    );
    sql = replaceExactlyOnce(
      sql,
      "VALUES (NEW.id, _role)",
      "VALUES (NEW.id, _role::public.app_role)",
      "new-user role cast for the fresh-install enum",
    );
  }

  if (name === reserveMigration) {
    sql = replaceOneMatch(
      sql,
      /CREATE TABLE IF NOT EXISTS public\.bank_reserve \([\s\S]*?\n\);\n\nINSERT INTO public\.bank_reserve/,
      `CREATE TABLE IF NOT EXISTS public.bank_reserve (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  balance numeric(18, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
  low_balance_threshold numeric(18, 2) NOT NULL DEFAULT 5000 CHECK (low_balance_threshold >= 0),
  currency text NOT NULL DEFAULT 'GYD',
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES auth.users(id)
);

INSERT INTO public.bank_reserve`,
      "bank reserve table layout",
    );
    sql = replaceOneMatch(
      sql,
      /CREATE TABLE IF NOT EXISTS public\.bank_reserve_ledger \([\s\S]*?\n\);/,
      `CREATE TABLE IF NOT EXISTS public.bank_reserve_ledger (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reserve_id integer NOT NULL DEFAULT 1 REFERENCES public.bank_reserve(id),
  entry_type text NOT NULL CHECK (entry_type IN (
    'funding', 'adjustment', 'agent_grant',
    'reserve_adjustment', 'reserve_to_agent', 'reserve_to_user'
  )),
  amount numeric(18, 2) NOT NULL CHECK (amount <> 0),
  balance_before numeric(18, 2) NOT NULL DEFAULT 0,
  balance_after numeric(18, 2) NOT NULL CHECK (balance_after >= 0),
  actor_id uuid NOT NULL REFERENCES auth.users(id),
  agent_id uuid REFERENCES auth.users(id),
  related_user_id uuid REFERENCES auth.users(id),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);`,
      "bank reserve ledger layout",
    );
    sql = replaceOneMatch(
      sql,
      /VALUES\s*\(\s*true\s*,\s*0\s*,\s*5000\s*\)/,
      "VALUES (1, 0, 5000)",
      "bank reserve singleton seed",
    );
    const booleanIdComparisons = [...sql.matchAll(/\bid\s*=\s*true\b/gi)].length;
    if (booleanIdComparisons < 3) {
      throw new Error(
        `Expected at least three boolean reserve-id comparisons; found ${booleanIdComparisons}`,
      );
    }
    sql = sql.replace(/\bid\s*=\s*true\b/gi, "id = 1");
  }

  transformed.push({ name, sql: sql.trimEnd() });
}

const overrides = (await readFile(overridesPath, "utf8")).trim();
const sections = transformed.map(
  ({ name, sql }) => `\n\n-- ===== Source migration: ${name} =====\n${sql}`,
);

const output = [
  "-- Generated by node scripts/build-supabase-update.mjs.",
  "-- Fresh Supabase project only: run once in the new project's SQL Editor.",
  "-- This schema bundle does not copy Auth users, stored files, secrets, or Edge Functions.",
  "-- See SUPABASE_FRESH_PROJECT_SETUP.md for the remaining setup steps.",
  "BEGIN;",
  ...sections,
  "\n\n-- ===== Fresh-project compatibility and app RPCs =====",
  overrides,
  "COMMIT;",
  "",
].join("\n");

await writeFile(outputPath, output, "utf8");
console.log(`Wrote SQL-update.sql from ${files.length} ordered migrations.`);
